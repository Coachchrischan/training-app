#!/usr/bin/env node
// Renders docs/TAC-GAME-DAY-LIBRARY.md from server/src/data/tac-gameday.json.
// The JSON is the source of truth (it also feeds /api/tac/gameday); the markdown
// is the version Chris reads on a phone or prints for a coach. Run after editing
// the JSON:  node scripts/render-gameday-doc.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(here, '..')
const data = JSON.parse(fs.readFileSync(path.join(root, 'server/src/data/tac-gameday.json'), 'utf8'))

const byId = Object.fromEntries(data.workouts.map(w => [w.id, w]))
const teamWord = n => ({ 2: 'Pairs', 3: 'Trios', 4: 'Quads' })[n] || `Teams of ${n}`
const auDate = iso => new Date(iso + 'T00:00:00').toLocaleDateString('en-AU', {
  weekday: 'long', day: 'numeric', month: 'long', year: 'numeric',
})

const out = []
const w = s => out.push(s)

w(`# TAC Game Day Library`)
w('')
w(`**${data.workouts.length} Community Day sessions for the ${data.room.name}.**`)
w('')
w(`Version ${data.version} · ${auDate(data.updated)} · ${data.club} · ${data.class}`)
w('')
w(`> Generated from \`server/src/data/tac-gameday.json\`. Edit the JSON, then run`)
w(`> \`node scripts/render-gameday-doc.mjs\`. Do not edit this file by hand.`)
w('')
w('---')
w('')

// ---- Room ----
w('## The room')
w('')
w(`Cap **${data.room.cap}**. ${data.room.note}`)
w('')
w('| Station | Count |')
w('|---|---|')
for (const [k, v] of Object.entries(data.room.stations)) {
  const label = { rower: 'Rowers', ski: 'SkiErgs', bike: 'Bikes', runner: 'Runners', sledLane: 'Sled lanes' }[k] || k
  w(`| ${label} | ${v} |`)
}
w('')
w(`**Correction:** ${data.room.previousAssumption}`)
w('')
w('Also on the floor: ' + data.room.floor.join(', ') + '.')
w('')
w('**Team maths for a full room:**')
w('')
for (const line of data.room.teamMaths) w(`- ${line}`)
w('')
w('---')
w('')

// ---- Engagement ----
w('## What "engaging" means here')
w('')
w(`> ${data.engagement.definition}`)
w('')
w('That definition produces rules, and every session in this library obeys them:')
w('')
data.engagement.rules.forEach((r, i) => w(`${i + 1}. ${r}`))
w('')
w(`**Session shape:** ${data.engagement.sessionShape}`)
w('')
w('**Lanes**')
w('')
for (const [k, v] of Object.entries(data.lanes)) {
  w(`- **${k[0].toUpperCase() + k.slice(1)}** — ${v}`)
}
w('')
w('---')
w('')

// ---- Picks ----
w('## The next three Saturdays')
w('')
w('Three picks out of the fifty, in a deliberate order: prove the layout, then add the noise, then')
w('make it an event.')
w('')
for (const p of data.picks) {
  const k = byId[p.workoutId]
  w(`### ${p.label} — ${auDate(p.date)}`)
  w('')
  w(`**${k.id} · ${k.name}** — ${teamWord(k.teamSize)}, ${k.teams}, ${k.durationMin} min`)
  w('')
  w(p.why)
  w('')
  w(`*Swap if:* ${p.swapIf}`)
  w('')
}
w('---')
w('')

// ---- Index ----
w('## Index')
w('')
w('| # | Session | Family | Team | Teams | Min |')
w('|---|---|---|---|---|---|')
for (const k of data.workouts) {
  w(`| ${k.id} | [${k.name}](#${k.id.toLowerCase()}-${k.name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}) | ${k.family} | ${teamWord(k.teamSize)} | ${k.teams} | ${k.durationMin} |`)
}
w('')
w('---')
w('')

// ---- Sessions ----
w('## The sessions')
w('')
for (const k of data.workouts) {
  w(`### ${k.id} · ${k.name}`)
  w('')
  w(`**${teamWord(k.teamSize)}** · ${k.teams} · ${k.durationMin} min · *${k.family}*`)
  w('')
  w(`**The hook.** ${k.engine}`)
  w('')
  w(`**Set-up.** ${k.stations}`)
  w('')
  w('**How it runs**')
  w('')
  for (const step of k.flow) w(`- ${step}`)
  w('')
  w(`**Score.** ${k.score}`)
  w('')
  w(`**Lanes.** Base: ${k.scaling.base}. Build: ${k.scaling.build}. Push: ${k.scaling.push}.`)
  w('')
  w('**Coach notes**')
  w('')
  for (const n of k.coachNotes) w(`- ${n}`)
  w('')
  w(`*Gear: ${k.gear.join(', ')}.*`)
  w('')
}

w('---')
w('')
w('*Companion documents: `TAC-COACH-HANDBOOK.md`, `TAC-COACH-REPORTING.md`, `TAC-OPS-TOOL.md`.*')
w('')

fs.writeFileSync(path.join(root, 'docs/TAC-GAME-DAY-LIBRARY.md'), out.join('\n'))
console.log(`Wrote docs/TAC-GAME-DAY-LIBRARY.md (${data.workouts.length} sessions, ${out.length} lines)`)
